function t(key) {
  const lang = TRANSLATIONS[currentLang] || TRANSLATIONS.de;
  return lang[key] || TRANSLATIONS.de[key] || key;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("myrights-lang", lang);
  applyTranslations();
}

function detectLanguage() {
  const saved = localStorage.getItem("myrights-lang");
  if (saved && TRANSLATIONS[saved]) return saved;
  const nav = (navigator.language || "de").slice(0, 2).toLowerCase();
  return TRANSLATIONS[nav] ? nav : "de";
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.documentElement.lang = currentLang;
}
